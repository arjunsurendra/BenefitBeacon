import fs from "node:fs";
import path from "node:path";
import { embedLocalText } from "../lib/local-vector";

type SeedProgram = {
  id: string;
  name: string;
  level: string;
  jurisdiction: string;
  cityScope: string[];
  category: string;
  summary: string;
  benefit: string;
  eligibilityText: string;
  applyUrl: string;
  sourceUrl: string;
  sourceLabel: string;
  sourceSnippet: string;
  interestTags: string[];
  audienceTags: string[];
  housingScope?: string;
  minAge?: number;
  maxAge?: number;
  incomeTargeted?: boolean;
  requiresChildren?: boolean;
  requiresDisability?: boolean;
  requiresVeteran?: boolean;
  requiresCaregiver?: boolean;
};

const workspace = process.cwd();
const sourcePath = path.join(workspace, "data/programs.seed.json");
const outputPath = path.join(workspace, "data/programs.seed.sql");
const programs = JSON.parse(fs.readFileSync(sourcePath, "utf8")) as SeedProgram[];
const checkedOn = process.env.BENEFITBEACON_SOURCE_CHECKED_ON || "2026-10-23";

function sql(value: unknown): string {
  if (value === undefined || value === null) return "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number") return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}

const ids = new Set<string>();
const statements = programs.map((program) => {
  if (ids.has(program.id)) throw new Error(`Duplicate program id: ${program.id}`);
  ids.add(program.id);
  if (!program.sourceUrl.startsWith("https://") || !program.applyUrl.startsWith("https://")) {
    throw new Error(`Program ${program.id} must use HTTPS source and application URLs.`);
  }
  const embeddingText = [program.name, program.category, program.summary, program.benefit, program.eligibilityText, ...program.interestTags, ...program.audienceTags].join(" ");
  const values = [
    program.id,
    program.name,
    program.level,
    program.jurisdiction,
    program.cityScope.join(","),
    program.category,
    program.summary,
    program.benefit,
    program.eligibilityText,
    program.applyUrl,
    program.sourceUrl,
    program.sourceLabel,
    program.sourceSnippet,
    program.interestTags.join(","),
    program.audienceTags.join(","),
    program.housingScope ?? "any",
    program.minAge,
    program.maxAge,
    program.incomeTargeted ?? false,
    program.requiresChildren ?? false,
    program.requiresDisability ?? false,
    program.requiresVeteran ?? false,
    program.requiresCaregiver ?? false,
    JSON.stringify(embedLocalText(embeddingText)),
    checkedOn,
    true,
  ];
  return `INSERT INTO programs (id, name, level, jurisdiction, city_scope, category, summary, benefit, eligibility_text, apply_url, source_url, source_label, source_snippet, interest_tags, audience_tags, housing_scope, min_age, max_age, income_targeted, requires_children, requires_disability, requires_veteran, requires_caregiver, embedding_json, last_checked, active) VALUES (${values.map(sql).join(", ")});`;
});

const output = [
  "-- Generated by scripts/build-program-seed.ts. Do not edit by hand.",
  "DELETE FROM programs;",
  ...statements,
  `-- ${programs.length} authoritative program records checked ${checkedOn}.`,
  "",
].join("\n");

fs.writeFileSync(outputPath, output);
console.log(`Prepared ${programs.length} program records in ${path.relative(workspace, outputPath)}.`);
